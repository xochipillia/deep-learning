#!/usr/bin/env python3
"""Regenerate results/comparison.{csv,json,md} from results/*/metrics.json.

    python scripts/build_comparison.py
"""
from __future__ import annotations

import csv
import json
import os
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
from stats_utils import paper_reference, wilson  # noqa: E402

REPL = Path(os.environ["REPL"])
PAPER = paper_reference()
ORDER = ["zero-shot", "self-consistency-1k", "self-consistency-2k", "guided-repair"]
LABELS = {
    "zero-shot": "Qwen3.5-4B zero-shot (official_short, guided choice)",
    "self-consistency-1k": "Qwen3.5-4B SC N=8, T=0.7, 1,024 tokens",
    "self-consistency-2k": "Qwen3.5-4B SC N=8, T=0.7, 2,048 tokens",
    "guided-repair": "SC N=8 2,048 tokens + official guided repair",
}


def row(name: str, m: dict) -> dict:
    ae, tr, rt, tk, g, c = m["answer_extraction"], m["truncation"], m["runtime"], m["tokens"], m["gpu"], m["aws_cost_estimate"]
    return {
        "configuration": name,
        "description": LABELS[name],
        "config_file": m.get("config"),
        "accuracy": m["accuracy"],
        "accuracy_pct": round(100 * m["accuracy"], 2) if m["accuracy"] is not None else None,
        "accuracy_ci95_low_pct": round(100 * wilson(m["correct"], m["total"])[0], 1),
        "accuracy_ci95_high_pct": round(100 * wilson(m["correct"], m["total"])[1], 1),
        "paper_full_val_accuracy_pct": PAPER["overall_accuracy_pct"].get(name),
        "correct": m["correct"],
        "total": m["total"],
        "question_extraction_failures": ae["question_level_failures"],
        "question_extraction_failure_rate": ae["question_level_failure_rate"],
        "chain_extraction_failures": ae["chain_level_failures"],
        "chain_extraction_failure_rate": ae["chain_level_failure_rate"],
        "truncated_chains": tr["chains_at_max_new_tokens"],
        "questions_with_truncated_chain": tr["questions_with_any_truncated_chain"],
        "generations_per_question": m["generations_per_question"],
        "avg_prompt_tokens_per_question_prefill": tk["avg_prompt_tokens_per_question_prefill"],
        "avg_prompt_tokens_per_question_summed_over_chains": tk["avg_prompt_tokens_per_question_summed_over_chains"],
        "avg_completion_tokens_per_question": tk["avg_completion_tokens_per_question"],
        "wall_clock_s": rt["wall_clock_s"],
        "cumulative_wall_clock_s": rt.get("cumulative_wall_clock_s_including_sc2k", rt["wall_clock_s"]),
        "avg_question_latency_s": rt["avg_question_latency_s"],
        "avg_wall_clock_per_question_s": rt["avg_wall_clock_per_question_s"],
        "peak_gpu_memory_used_gib": g.get("peak_gpu_memory_used_gib"),
        "instance_hours": c["instance_hours"],
        "est_compute_usd": c["compute_usd"],
        "est_ebs_usd_during_run": c["ebs_storage_usd_during_run"],
        "verification_passed": m["verification"]["all_checks_passed"],
    }


def main() -> None:
    rows = []
    for name in ORDER:
        p = REPL / "results" / name / "metrics.json"
        if p.exists():
            rows.append(row(name, json.loads(p.read_text())))
    out = REPL / "results"
    (out / "comparison.json").write_text(json.dumps(rows, indent=2, ensure_ascii=False))
    with open(out / "comparison.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader(); w.writerows(rows)
    cols = [("configuration", "Configuration"), ("accuracy_pct", "Acc. %"), ("ci95", "95% CI (Wilson)"),
            ("paper_full_val_accuracy_pct", "Paper val-full %"), ("correct", "Correct"), ("total", "Total"),
            ("question_extraction_failures", "Q. extr. fail"), ("chain_extraction_failure_rate", "Chain extr. fail rate"),
            ("truncated_chains", "Truncated chains"), ("generations_per_question", "Gens/q"),
            ("avg_prompt_tokens_per_question_prefill", "Prompt tok/q"),
            ("avg_completion_tokens_per_question", "Completion tok/q"), ("wall_clock_s", "Wall s"),
            ("avg_question_latency_s", "s/q"), ("peak_gpu_memory_used_gib", "Peak GPU GiB"),
            ("est_compute_usd", "Compute $"), ("verification_passed", "Checks")]
    md = ["# Comparison (seed-42 stratified 200-question EXAMS-V validation subset)", "",
          "Generated by `scripts/build_comparison.py` from `results/*/metrics.json`.", "",
          "| " + " | ".join(h for _, h in cols) + " |", "|" + "---|" * len(cols)]
    for r in rows:
        r = {**r, "ci95": f"[{r['accuracy_ci95_low_pct']}, {r['accuracy_ci95_high_pct']}]"}
        md.append("| " + " | ".join("" if r[k] is None else str(r[k]) for k, _ in cols) + " |")
    md += ["", "Definitions:",
           "- 95% CI (Wilson): Wilson score interval for accuracy on the 200 questions.",
           "- Paper val-full %: accuracy reported by the authors on the full validation split (n=4,651), from the",
           "  official README; context only, not a target for a 200-question subset.",
           "- Q. extr. fail: questions where no chain yielded an extractable letter (prediction is null and counted wrong).",
           "- Chain extr. fail rate: fraction of generated chains where the official `extract_answer` returned None.",
           "- Truncated chains: chains whose completion length reached `max_new_tokens`.",
           "- Prompt tok/q: prefill length (image + text) per question; with N=8 the prefill is shared by all chains.",
           "- Completion tok/q: completion tokens summed over all chains of a question.",
           "- Wall s: wall clock of the full runner process including model load and dataset loading.",
           "- s/q: mean per-question latency recorded by the official runner (`total_latency_s`).",
           "- Peak GPU GiB: max nvidia-smi memory.used during the run; vLLM pre-allocates 90% of GPU memory.",
           "- Compute $: wall-clock hours x $2.80/h (ml.g6e.2xlarge Studio JupyterLab, us-east-1).",
           "- guided-repair: wall clock is the repair pass only; see `cumulative_wall_clock_s` in the CSV/JSON."]
    (out / "comparison.md").write_text("\n".join(md) + "\n")
    by_language(rows)
    print("\n".join(md))


def by_language(rows: list[dict]) -> None:
    """results/by-language.{csv,json,md}: per-language correct/total, Wilson CI and the paper's Table 10."""
    out, ref = REPL / "results", PAPER["by_language_accuracy_pct"]
    names = [r["configuration"] for r in rows]
    data = {n: json.loads((out / n / "metrics.json").read_text())["by_language"] for n in names}
    langs = sorted(set().union(*[d.keys() for d in data.values()]))
    table = []
    for lang in langs:
        row = {"language": lang, "n_subset": next(d[lang]["total"] for d in data.values() if lang in d),
               "n_full_validation": PAPER["by_language_n_full_validation"].get(lang)}
        for n in names:
            v = data[n].get(lang)
            if v:
                lo, hi = v["ci95_wilson"]
                row[f"{n}_correct"] = v["correct"]
                row[f"{n}_pct"] = round(100 * v["accuracy"], 1)
                row[f"{n}_ci95"] = f"[{100 * lo:.1f}, {100 * hi:.1f}]"
        for n in ("self-consistency-1k", "self-consistency-2k"):
            row[f"paper_{n}_pct"] = ref.get(n, {}).get(lang)
        table.append(row)
    (out / "by-language.json").write_text(json.dumps(table, indent=2, ensure_ascii=False))
    with open(out / "by-language.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(table[0].keys())); w.writeheader(); w.writerows(table)
    hdr = ["Language", "n"] + [f"{n} %" for n in names] + [f"{n} 95% CI" for n in ("self-consistency-1k", "self-consistency-2k") if n in names] \
          + ["Paper SC-1k %", "Paper SC-2k %"]
    md = ["# Accuracy by language (200-question subset) vs. paper Table 10 (full validation)", "",
          "Generated by `scripts/build_comparison.py`. Paper columns: arXiv:2607.09438, Appendix G, Table 10 (Q3.5 SC N=8),",
          "measured on the full validation split. With 12-22 questions per language here, the per-language",
          "confidence intervals are very wide; differences from the paper are not interpretable individually.", "",
          "| " + " | ".join(hdr) + " |", "|" + "---|" * len(hdr)]
    for r in table:
        cells = [r["language"], str(r["n_subset"])] + [str(r.get(f"{n}_pct", "")) for n in names] \
                + [r.get(f"{n}_ci95", "") for n in ("self-consistency-1k", "self-consistency-2k") if n in names] \
                + [str(r["paper_self-consistency-1k_pct"]), str(r["paper_self-consistency-2k_pct"])]
        md.append("| " + " | ".join(cells) + " |")
    (out / "by-language.md").write_text("\n".join(md) + "\n")


if __name__ == "__main__":
    main()
